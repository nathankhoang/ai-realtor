/**
 * Seeds scripts/vision-eval/labels.json with N random listings that
 * already have a stored vision analysis, using each analysis as the
 * strawman ground truth for that listing.
 *
 *   npx tsx scripts/vision-eval/seed-smoke-labels.ts          # default 25 listings
 *   npx tsx scripts/vision-eval/seed-smoke-labels.ts 10       # custom count
 *
 * Purpose: end-to-end test of the eval pipeline against a
 * meaningfully-sized sample without requiring human labeling.
 *
 * Caveat: whichever model produced the stored analyses (Sonnet by
 * default in production) will score artificially high against itself.
 * Use the score column for directional signal only — for absolute
 * quality, hand-label real listings. The Markdown comparison report
 * the eval emits is the better surface for judging quality.
 */
import { config as dotenvConfig } from 'dotenv'
dotenvConfig({ path: '.env.local' })

import { Pool } from '@neondatabase/serverless'
import { writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

interface StoredFeatures {
  floors?: { type?: string }
  kitchenCountertops?: { type?: string }
  kitchenAppliances?: { type?: string }
  ceilings?: { height?: string }
  naturalLight?: { condition?: string }
  overallAge?: string
}

const __dirname = dirname(fileURLToPath(import.meta.url))

function deriveGroundTruth(f: StoredFeatures): Record<string, string> {
  const gt: Record<string, string> = {}
  if (f.floors?.type && f.floors.type !== 'unknown') gt.floorType = f.floors.type
  if (f.kitchenCountertops?.type && f.kitchenCountertops.type !== 'unknown') {
    gt.countertopType = f.kitchenCountertops.type
  }
  if (f.kitchenAppliances?.type && f.kitchenAppliances.type !== 'unknown') {
    gt.appliancePalette = f.kitchenAppliances.type
  }
  if (f.ceilings?.height && f.ceilings.height !== 'unknown') {
    gt.ceilingHeight = f.ceilings.height
  }
  if (f.naturalLight?.condition && f.naturalLight.condition !== 'unknown') {
    gt.naturalLight = f.naturalLight.condition
  }
  if (f.overallAge && f.overallAge !== 'unknown') gt.overallAge = f.overallAge
  return gt
}

async function main() {
  if (!process.env.DATABASE_URL) {
    console.error('DATABASE_URL not set. Run `vercel env pull .env.local` first.')
    process.exit(1)
  }

  // First positional arg = listing count. Default 25 — enough sample to
  // get directional signal without huge API spend.
  const requested = Number(process.argv[2] ?? '25')
  const count = Number.isFinite(requested) && requested > 0 ? Math.floor(requested) : 25

  const pool = new Pool({ connectionString: process.env.DATABASE_URL })

  // Over-fetch by 2× to compensate for listings whose stored analysis is
  // all-"unknown" (we drop those — they have nothing to score against).
  const result = await pool.query(
    `
    SELECT
      l.zillow_id,
      l.address,
      l.photo_urls,
      la.features_json
    FROM listings l
    JOIN listing_analyses la ON la.listing_id = l.id
    WHERE l.photo_urls IS NOT NULL
      AND jsonb_array_length(l.photo_urls) >= 4
    ORDER BY random()
    LIMIT $1
  `,
    [count * 2],
  )
  await pool.end()

  type Row = {
    zillow_id: string
    address: string
    photo_urls: string[]
    features_json: StoredFeatures
  }

  const rows = result.rows as Row[]
  const usable: Array<{ row: Row; groundTruth: Record<string, string> }> = []
  for (const row of rows) {
    const gt = deriveGroundTruth(row.features_json)
    if (Object.keys(gt).length === 0) continue
    usable.push({ row, groundTruth: gt })
    if (usable.length >= count) break
  }

  if (usable.length === 0) {
    console.error('No listings with usable stored analyses found in your DB.')
    process.exit(1)
  }

  const labels = {
    _doc: `AUTO-GENERATED by seed-smoke-labels.ts. groundTruth in each listing comes from the stored vision analysis (Sonnet by default in production), so Sonnet will score artificially high against itself. Use the score column for directional signal only; use the Markdown comparison report for quality judgment.`,
    listings: usable.map(({ row, groundTruth }) => ({
      zillowId: row.zillow_id,
      addressNote: row.address,
      groundTruth,
      judgmentCalls: [],
    })),
  }

  const outPath = join(__dirname, 'labels.json')
  await writeFile(outPath, JSON.stringify(labels, null, 2), 'utf-8')

  console.log(`Wrote ${outPath}`)
  console.log(`  ${usable.length} listings (${rows.length - usable.length} dropped for empty analysis)`)
  console.log('')
  console.log('Next: npx tsx scripts/vision-eval/eval.ts')
}

main().catch((err) => {
  console.error('seed failed:', err)
  process.exit(1)
})
